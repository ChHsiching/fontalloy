/**
 * Recipe YAML generation: draft -> the exact schema
 * `fontalloy_core.load_recipe` parses (see `core/fontalloy_core/recipe.py`).
 *
 * The writer is hand-rolled on purpose — no dependency, and full control
 * over determinism (sorted nothing, no timestamps: identical builder
 * state must produce byte-identical YAML, mirroring the reproducible
 * build rule). Strings that can carry YAML-significant characters
 * (paths with `#`, ranges with `-`) are always double-quoted; validated
 * family names and fc-lang set names are emitted bare; codepoints are
 * YAML 1.1 hex integers, which `yaml.safe_load` reads as ints.
 *
 * Pinned from both ends: `tests/test_webapp_recipe.py` proves the
 * checked-in sample parses through the strict loader; the seam-3 web
 * suite proves the builder emits it.
 */

import { fontRef, type RecipeDraft } from "./model";
import { normalizeFamilyName } from "./validate";

/**
 * The output block as written: the family normalized exactly like the
 * core normalizes it on load (spaces -> hyphens), so the emitted file is
 * canonical and load-identical either way.
 */
function normalizeOutput(draft: RecipeDraft): {
  family: string;
  format: string;
} {
  return {
    family: normalizeFamilyName(draft.output.family),
    format: draft.output.format,
  };
}

/** Double-quoted YAML scalar with `"` and `\` escaped. */
function quote(value: string): string {
  return `"${value.replace(/\\/g, "\\\\").replace(/"/g, '\\"')}"`;
}

/** Uppercase `0x`-prefixed hex (YAML 1.1 integer form). */
function hex(value: number): string {
  return `0x${value.toString(16).toUpperCase()}`;
}

function flowList(values: string[]): string {
  return `[${values.join(", ")}]`;
}

/**
 * The recipe document for `draft`. Incomplete rules are the editor's
 * business (validation gates download/copy); the writer emits the draft
 * as declared.
 */
export function recipeYaml(draft: RecipeDraft): string {
  const lines: string[] = [];
  lines.push("# FontAlloy recipe — generated by the WebApp recipe builder.");
  lines.push(`base: ${quote(fontRef(draft.base))}`);
  lines.push(
    draft.donors.length === 0
      ? "donors: []"
      : "donors:\n" +
          draft.donors.map((slot) => `  - ${quote(fontRef(slot))}`).join("\n"),
  );

  const rules = draft.rules.map((rule) => {
    const target =
      rule.target.kind === "preset"
        ? `set: ${rule.target.name}`
        : rule.target.kind === "range"
          ? `range: ${quote(`${hex(rule.target.start)}-${hex(rule.target.end)}`)}`
          : `codepoint: ${hex(rule.target.cp)}`;
    return `  - ${target}\n    fonts: ${flowList(rule.fonts)}`;
  });
  lines.push(rules.length === 0 ? "rules: []" : "rules:\n" + rules.join("\n"));

  const { family, format } = normalizeOutput(draft);
  lines.push("output:");
  lines.push(`  format: ${format}`);
  lines.push(`  family: ${family}`);
  return lines.join("\n") + "\n";
}

/** Recipe file name derived from the validated output family. */
export function recipeFileName(draft: RecipeDraft): string {
  const { family } = normalizeOutput(draft);
  return `${family || "fontalloy-recipe"}.yaml`;
}

/** The CLI command that reproduces the same merge from this draft. */
export function buildCommand(draft: RecipeDraft): string {
  return `fontalloy build ${recipeFileName(draft)}`;
}
